/** The concurrent players the tables show, around the clock. */
export const POPULATIONS = [5, 50, 200, 1000, 10_000] as const;
/** The crowds the headroom section follows from a fresh day (ADR 0075). */
export const CROWDS = [50, 200, 621] as const;

/** The parts of a saved `/v1/metrics` answer that replace assumptions. */
export interface MetricsInput {
  today: {
    playerMs: number;
    messages: number;
    requests: number;
    rowsWritten: number;
    rowsRead: number;
    relay: { kb: number };
  };
}

const HOUR_MS = 3_600_000;

/** What a saved `/v1/metrics` answer measures live, as overrides of the per-player rates. */
export function overridesFrom(metrics: MetricsInput | null): Partial<Rates> {
  if (metrics === null || metrics.today.playerMs <= 0) return {};
  const hours = metrics.today.playerMs / HOUR_MS;
  return {
    messagesPerHour: metrics.today.messages / hours,
    requestsPerHour: metrics.today.requests / hours,
    rowsWrittenPerHour: metrics.today.rowsWritten / hours,
    rowsReadPerHour: metrics.today.rowsRead / hours,
    turnGbPerHour: metrics.today.relay.kb / 1e6 / hours,
  };
}

const n0 = (n: number) => Math.round(n).toLocaleString('en');
const n1 = (n: number) =>
  n.toLocaleString('en', { minimumFractionDigits: 1, maximumFractionDigits: 1 });
const n2 = (n: number) =>
  n.toLocaleString('en', { minimumFractionDigits: 2, maximumFractionDigits: 2 });
const usd = (n: number) => `$${n2(n)}`;
const bytes = (n: number) =>
  n >= 1e9
    ? `${n1(n / 1e9)} GB`
    : n >= 1e6
      ? `${n1(n / 1e6)} MB`
      : n >= 1e3
        ? `${n1(n / 1e3)} KB`
        : `${n0(n)} B`;
const pct = (n: number) => `${n1(100 * n)}%`;

function table(rows: string[][]): string {
  const [head, ...body] = rows;
  if (!head) return '';
  return [
    `| ${head.join(' | ')} |`,
    `|${head.map(() => '---').join('|')}|`,
    ...body.map((r) => `| ${r.join(' | ')} |`),
  ].join('\n');
}

